globalThis.Hooks = { on() {}, once() {}, off() {}, call() {}, callAll() {} };
globalThis.ui = { notifications: { warn() {}, info() {} } };
const { ContactRepository } = await import('../../../scripts/data/ContactRepository.js');
const { MessageComposerApp } = await import('../../../scripts/ui/MessageComposer/MessageComposerApp.js');
const repo = Object.create(ContactRepository.prototype);
repo.getContacts = async (id) => actors.get(id).getFlag(MID, 'contacts') || [];
const search = async (q) => { const t = { contactRepo: repo, recipients: [], fromActorId: 'v', networkService: null, contactGroupService: null, _closeAutocomplete() {}, _renderAutocomplete() {}, _sendingNpcId: MessageComposerApp.prototype._sendingNpcId }; await MessageComposerApp.prototype._searchRecipients.call(t, q); return t._searchResults; };
