const npc = mk('rogue', 'Rogue', 'rogue@nc.net', false);
const pal = mk('jackie', 'Jackie', 'jackie@nc.net', true);
const alias = { id: 'c1', name: 'Silver', email: 'silver@nc.net', masterContactId: 'm-silver', tags: [] };
const v = mk('v', 'V', 'v@nc.net', true, [alias]);
const list = [npc, pal, v];
const actors = Object.assign([...list], { get: (id) => list.find((a) => a.id === id) });
globalThis.game = { user: { id: 'u1', isGM: false }, actors, users: [], settings: { get: () => { throw new Error('none'); } }, nightcity: { masterContactService: { isSendOnly: () => false, search: () => [{ id: 'm-rogue', name: 'Rogue', email: 'rogue@nc.net', actorId: 'rogue' }, { id: 'm-silver', name: 'Silver', email: 'silver@nc.net', actorId: 'rogue' }] } } };
